  static PlanTemplateDay _day(
    int dayOffset,
    String title,
    String focus,
    List<String> exerciseIds,
  ) {
    return PlanTemplateDay(
      dayOffset: dayOffset,
      title: title,
      focus: focus,
      exercises: exerciseIds.indexed.map((indexed) {
        final index = indexed.$1;
        final id = indexed.$2;
        final exercise = exercises.firstWhere(
          (exercise) => exercise.id.value == id,
        );
        return TemplateExercise(
          exerciseId: exercise.id,
          sets: index == 0 && exercise.muscleGroup == MuscleGroup.cardio
              ? 1
              : exercise.defaultSets,
          repRange: exercise.defaultRepRange,
          durationMinutes: exercise.defaultDurationMinutes,
          restSeconds: exercise.restSeconds,
          note: exercise.difficulty == DifficultyLevel.beginner
              ? '자세가 안정되면 다음 주에 1-2회만 늘려보세요.'
              : 'RPE 7-8 안에서 자세가 무너지지 않는 선까지만 진행하세요.',
        );
      }).toList(),
    );
  }
